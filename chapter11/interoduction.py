# Topic 1: What is Inheritance?

# Inheritance is a feature where one class (child class) acquires the properties and methods of another class (parent class).

# Real-Life Example
#           Animal
#              │
#       ----------------
#       │              │
#      Dog            Cat
# Dog is an Animal.
# Cat is an Animal.

# Both inherit common features from Animal.

# Advantages
# Code Reusability
# Easy Maintenance
# Less Code Duplication
# Better Organization